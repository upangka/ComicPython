"""常用分割线字符参考

运行此文件查看所有可用的分割线字符。
"""

print("常用分割线字符参考")
print("=" * 60)

lines = [
    ("普通减号", "-"),
    ("下划线", "_"),
    ("细横线 (─)", "─"),
    ("粗横线 (━)", "━"),
    ("双横线 (═)", "═"),
    ("波浪线 (〜)", "〜"),
    ("星号线", "*"),
    ("等号线", "="),
]

for name, char in lines:
    print(f"{name:20s}: {char * 50}")

print("\n复制使用方法：")
print("# 在代码中直接使用这些字符")
print('print("─" * 50)  # 细横线')
print('print("━" * 50)  # 粗横线')
print('print("═" * 50)  # 双横线')
