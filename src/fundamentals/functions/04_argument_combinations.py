def func(a, b, c, d, e, f):
    print(f"{a=} {b=} {c=} {d=} {e=} {f=}")

# 普通位置参数与可迭代对象拆包混合
func(*(1, 2), 3, 5, *[4], **{'f': 6})

# 关键字参数与可迭代对象拆包混合
func(f=6, *[1, 2, 3, 4, 5])
func(1, e=4, *(2, 3), *(5,), **{'f': 6})

# 字典拆包与关键字参数混合
func(1, **{'c': 3, 'e': 5}, d=3, **{'f': 6}, b=2, )
func(1, **{'b': 2, 'c': 3}, d=4, **{'e': 5, 'f': 6})
func(*(1, 2), e=5, *[3, 4], f=6)
