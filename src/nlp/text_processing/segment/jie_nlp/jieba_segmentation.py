import warnings

warnings.filterwarnings('ignore', category=SyntaxWarning)
import jieba


def demo_precise_mode(text: str) -> list[str]:
    """
    精确模式（默认）
    原理：每个位置只切一刀，给出最合理的分词结果
    场景：文本分析、词频统计、情感分析
    """
    tokens = jieba.lcut(text)
    print(f"【精确模式】")
    print(f"  结果：{' / '.join(tokens)}")
    print(f"  词数：{len(tokens)}")
    return tokens


def demo_full_mode(text: str) -> list[str]:
    """
    全模式
    原理：把所有可能成词的组合全部扫描出来，有冗余
    场景：需要高召回率、穷举所有可能的词组
    """
    tokens = jieba.lcut(text, cut_all=True)
    print(f"【全模式】")
    print(f"  结果：{' / '.join(tokens)}")
    print(f"  词数：{len(tokens)}")
    return tokens


def demo_search_mode(text: str) -> list[str]:
    """
    搜索引擎模式
    原理：在精确模式基础上，对长词再次切分
    场景：搜索引擎索引构建、关键词提取
    """
    tokens = jieba.lcut_for_search(text)
    print(f"【搜索引擎模式】")
    print(f"  结果：{' / '.join(tokens)}")
    print(f"  词数：{len(tokens)}")
    return tokens


def highlight_diff(tokens_exact: list[str], tokens_full: list[str], tokens_search: list[str]) -> None:
    """
    高亮显示三种模式的差异词
    """
    # 找出全模式多余的词
    only_in_full = set(tokens_full) - set(tokens_exact)
    # 找出搜索引擎模式比精确模式多出的词
    only_in_search = set(tokens_search) - set(tokens_exact)

    print(f"\n{'─' * 55}")
    print(f"全模式冗余词（精确模式没有的）：{only_in_full if only_in_full else '无'}")
    print(f"搜索引擎模式新增词（精确模式没有的）：{only_in_search if only_in_search else '无'}")
    print(f"{'─' * 55}")


def compare_all_modes(text: str) -> None:
    """
    对同一段文本，运行三种模式并对比
    """
    print(f"\n{'=' * 55}")
    print(f"📖 原文：{text}")
    print(f"{'=' * 55}")

    tokens_exact = demo_precise_mode(text)
    tokens_full = demo_full_mode(text)
    tokens_search = demo_search_mode(text)

    highlight_diff(tokens_exact, tokens_full, tokens_search)


if __name__ == '__main__':
    compare_all_modes("周六下午我去深圳图书馆自习，看了三本Python编程书")
    compare_all_modes("深圳图书馆北馆在龙华区，环境特别好")
    compare_all_modes("我在深圳图书馆听了人工智能讲座，学到了很多知识")


